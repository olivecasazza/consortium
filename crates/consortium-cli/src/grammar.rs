//! CLI grammar: one introspected source of truth for the command surface.
//!
//! Ports the lazaret `nu/grammar.nu` idea (INTERFACE / dump / violations /
//! check) onto clap: every signature fact comes from each bin's
//! `Args::command()` via `clap::CommandFactory` — never a hand-maintained
//! list. `check` fails on any new violation and on any baseline entry that
//! no longer reproduces, so the baseline can only shrink.
//!
//! Rules enforced by [`violations`]:
//!
//! - `global-flags` — introspected bins expose exactly the pinned root
//!   long-option vocabulary ([`PINNED_ROOT_LONGS`]); missing and
//!   unexpected spellings both violate.
//! - `selector` — selector (node/set-selection) options match
//!   [`PINNED_SELECTORS`] exactly per `(bin, subcommand)`; missing and
//!   unexpected selectors both violate. molt pins an empty set; cast
//!   subcommands are strict whitelists.
//! - `registry` — every bin maps to an existing source file and ships a
//!   `tests/<bin>_tests.rs`.
//! - `compat` — claw/molt/pinch short flags equal the frozen upstream
//!   ClusterShell sets (parity is pinned by the `consortium-tests` oracle).
//! - `typed` — every introspected argument carries help text.

use std::borrow::Cow;
use std::collections::BTreeSet;
use std::path::Path;

// Build-time `[[bin]]` registry facts (name, declared path, source/test
// presence) generated by build.rs from Cargo.toml, so runtime checks
// never stat the build source tree.
include!(concat!(env!("OUT_DIR"), "/grammar_registry.rs"));

/// One build-time `[[bin]]` fact generated into the included file.
pub(crate) struct RegistryFact {
    pub name: &'static str,
    pub path: &'static str,
    pub source_exists: bool,
    pub tests_exist: bool,
}

