/// `global-flags` rule against exact root long spellings: every pinned
/// long must be present and no unexpected long may appear. Compares
/// `Row.long` (not arg IDs), so a renamed spelling for an existing
/// argument ID violates both as missing and as unexpected.
fn global_flags(rows: &[Row], out: &mut Vec<Violation>) {
    for (bin, pinned) in PINNED_ROOT_LONGS {
        let want: BTreeSet<&str> = pinned.iter().copied().collect();
        let got: BTreeSet<&str> = rows
            .iter()
            .filter(|r| {
                r.bin == *bin
                    && r.subcommand.is_empty()
                    && r.kind != "registry"
                    && r.arg != "help"
                    && r.arg != "version"
            })
            .filter_map(|r| r.long.as_deref())
            .collect();
        for missing in want.difference(&got) {
            out.push(Violation {
                rule: "global-flags".to_string(),
                subcommand: String::new(),
                bin: (*bin).to_string(),
                arg: (*missing).to_string(),
                detail: "pinned root long option missing".to_string(),
            });
        }
        for unexpected in got.difference(&want) {
            out.push(Violation {
                rule: "global-flags".to_string(),
                subcommand: String::new(),
                bin: (*bin).to_string(),
                arg: (*unexpected).to_string(),
                detail: "unexpected root long option".to_string(),
            });
        }
    }
}

/// Long options that are shared OutputArgs or clap built-ins, never
/// selectors.
const NON_SELECTOR_LONGS: &[&str] = &["verbose", "color", "format", "help", "version"];

/// `selector` rule over exact `(bin, subcommand)` sets. A candidate is
/// any root/subcommand row with a long spelling outside
/// [`NON_SELECTOR_LONGS`]. Candidates in the cross-bin vocabulary but not
/// pinned at their location violate as unexpected; on `cast` (strict)
/// any unpinned candidate violates. Pinned selectors absent from the
/// live grammar violate as missing. Rows are keyed per subcommand, so
/// `cast build --on` and `cast deploy --on` are distinct.
fn selectors(rows: &[Row], out: &mut Vec<Violation>) {
    // Cross-bin "selector-like" vocabulary: selection names from every
    // pinned set, minus execution options shared across commands
    // (fanout, builders, cascade...). molt --on must violate even though
    // `on` is pinned only on cast; claw --fanout must not, because
    // fanout is delivery, not node selection. `cast` subcommands are
    // pinned exactly by their own strict whitelists.
    let exec_options: [&str; 4] = ["fanout", "builders", "cascade", "cascade-fanout"];
    let vocab: BTreeSet<&str> = PINNED_SELECTORS
        .iter()
        .flat_map(|(_, _, longs)| longs.iter().copied())
        .filter(|l| !exec_options.contains(l))
        .collect();
    for (bin, sub, pinned) in PINNED_SELECTORS {
        let want: BTreeSet<&str> = pinned.iter().copied().collect();
        let candidates: BTreeSet<&str> = rows
            .iter()
            .filter(|r| {
                r.bin == *bin
                    && r.subcommand == *sub
                    && r.kind != "registry"
                    && r.kind != "positional"
            })
            .filter_map(|r| r.long.as_deref())
            .filter(|l| !NON_SELECTOR_LONGS.contains(l))
            .collect();
        for missing in want.difference(&candidates) {
            out.push(Violation {
                rule: "selector".to_string(),
                subcommand: (*sub).to_string(),
                bin: (*bin).to_string(),
                arg: (*missing).to_string(),
                detail: "pinned selector missing from the live grammar".to_string(),
            });
        }
        let strict = *bin == "cast";
        for unexpected in candidates.difference(&want) {
            if vocab.contains(unexpected) || strict {
                out.push(Violation {
                    rule: "selector".to_string(),
                    subcommand: (*sub).to_string(),
                    bin: (*bin).to_string(),
                    arg: (*unexpected).to_string(),
                    detail: if strict {
                        "cast subcommand selector outside the pinned whitelist".to_string()
                    } else {
                        "selector-like option not allowed on this command".to_string()
                    },
                });
            }
        }
    }
}

/// Interface rules evaluated against the live grammar.
pub fn violations() -> Vec<Violation> {
    let rows = dump();
    let mut v = Vec::new();

    global_flags(&rows, &mut v);

    selectors(&rows, &mut v);

    // Embedded build-time facts: no stat of the build source tree.
    v.extend(registry_findings(Ok::<_, anyhow::Error>(
        embedded_registry(),
    )));

    for (bin, pinned) in PINNED_SHORT_FLAGS {
        let got: BTreeSet<char> = rows
            .iter()
            .filter(|r| r.bin == *bin && !SHARED_FLAGS.contains(&r.arg.as_str()))
            .filter_map(|r| r.short)
            .collect();
        let want: BTreeSet<char> = pinned.chars().collect();
        if got != want {
            v.push(Violation {
                rule: "compat".to_string(),
                subcommand: String::new(),
                bin: (*bin).to_string(),
                arg: "short-flags".to_string(),
                detail: format!("frozen upstream set drift: got {got:?} want {want:?}"),
            });
        }
    }

    typed_missing_help(&rows, &mut v);

    v
}

/// `typed` rule: every introspected argument (excluding `help`/`version`
/// and non-introspected registry rows) must carry help text. Keyed per
/// `bin subcommand arg`, so the same argument ID on distinct subcommands
/// yields distinct violations.
fn typed_missing_help(rows: &[Row], out: &mut Vec<Violation>) {
    out.extend(
        rows.iter()
            .filter(|r| {
                r.kind != "registry" && r.help.is_empty() && r.arg != "help" && r.arg != "version"
            })
            .map(|r| Violation {
                rule: "typed".to_string(),
                subcommand: r.subcommand.clone(),
                bin: r.bin.clone(),
                arg: r.arg.clone(),
                detail: "argument has no help text".to_string(),
            }),
    );
}

/// Pure new-vs-stale comparison over baseline keys: errors when the live
/// set has keys the baseline lacks (new violations) or the baseline has
/// keys that no longer reproduce (stale entries — the baseline can only
/// shrink). Returns the live violation count on success.
pub fn check_keys(live: &[String], baseline: &[String]) -> anyhow::Result<usize> {
    let live_set: BTreeSet<&String> = live.iter().collect();
    let baseline_set: BTreeSet<&String> = baseline.iter().collect();
    if live_set.len() != live.len() {
        return Err(anyhow::anyhow!(
            "grammar check failed: duplicate keys in live set: {live:?}"
        ));
    }
    if baseline_set.len() != baseline.len() {
        return Err(anyhow::anyhow!(
            "grammar check failed: duplicate keys in baseline: {baseline:?}"
        ));
    }
    let new: Vec<&String> = live_set.difference(&baseline_set).copied().collect();
    let stale: Vec<&String> = baseline_set.difference(&live_set).copied().collect();
    if !new.is_empty() || !stale.is_empty() {
        return Err(anyhow::anyhow!(
            "grammar check failed: {new_count} new, {stale_count} stale\nnew: {new:?}\nstale: {stale:?}",
            new_count = new.len(),
            stale_count = stale.len()
        ));
    }
    Ok(live.len())
}

/// Result of comparing the live grammar against a baseline.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct CheckReport {
    pub ok: bool,
    pub baseline: usize,
    pub violations: usize,
}

/// Compare live violations with the baseline file (JSON array of
/// `rule bin subcommand arg` keys, root level marked [`ROOT`]). Errors on
/// new, stale, or duplicate entries.
pub fn check(baseline: &Path) -> anyhow::Result<CheckReport> {
    let source = std::fs::read_to_string(baseline).with_context(|| {
        format!(
            "grammar check failed: cannot read baseline {}",
            baseline.display()
        )
    })?;
    let base: Vec<String> = serde_json::from_str(&source)?;
    let live = violations();
    let keys: Vec<String> = live.iter().map(key_of).collect();
    let count = check_keys(&keys, &base)?;
    Ok(CheckReport {
        ok: true,
        baseline: base.len(),
        violations: count,
    })
}

